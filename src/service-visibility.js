const retiredIds=new Set(RETIRED_PRACTICAL_IDS);
export function isRetiredPractical(item) {
  return !!item&&(retiredIds.has(item.questionId)||(item.type==='practical'&&!item.practicalTask));
}
export function hasRetiredPractical(session) {
  return !!session?.items?.some(isRetiredPractical);
}
/** Apply before current lists/counts/search or selection; do not overwrite stored originals. */
export function serviceBank(bank) {
  return bank?{...bank,questions:bank.questions.filter(q=>!isRetiredPractical(q))}:null;
}
